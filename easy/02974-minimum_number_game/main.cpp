std::vector<int> numberGame(std::vector<int> nums)
{
  std::sort(nums.begin(), nums.end());
  for (size_t i = 0; i < nums.size() - 1; i += 2)
    std::swap(nums[i], nums[i + 1]);
  return nums;
}
//----------------------------------------------------------------------------------------------------------------------
int main()
{
  std::cout << "minimum number game" << std::endl;

  std::cout << numberGame({5, 4, 2, 3}); // [3, 2, 5, 4]
  std::cout << numberGame({2, 5}); // [5, 2]

  return 0;
}
