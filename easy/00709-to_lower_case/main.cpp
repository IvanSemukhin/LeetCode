#include <iostream>
//----------------------------------------------------------------------------------------------------------------------
std::string toLowerCase(std::string & s)
{
  for (auto & ch : s)
    if (ch >= 'A' && ch <= 'Z')
      ch += 'a' - 'A';
  return s;
}
//----------------------------------------------------------------------------------------------------------------------
int main()
{
  std::cout << "to lower case" << std::endl;

  std::string hello = "HELLO";
  std::cout << toLowerCase(hello) << std::endl;

  return 0;
}
